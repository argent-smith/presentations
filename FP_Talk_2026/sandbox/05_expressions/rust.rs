// Rust: match — выражение; точка с запятой превращает выражение в инструкцию
// Полнота перебора — обязательна, иначе ошибка компиляции
fn classify(n: i32) -> &'static str {
    match n {
        n if n < 0 => "negative",
        0          => "zero",
        _          => "positive",
    }  // без точки с запятой — значение возвращается из функции
}

fn main() {
    for n in [-3, 0, 5] {
        println!("{} → {}", n, classify(n));
    }
}
